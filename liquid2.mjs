import { chromium, devices } from '@playwright/test';
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
await page.goto('http://localhost:4173/', { waitUntil: 'networkidle' });
await page.waitForTimeout(400);
await page.getByRole('button', { name: /Experiment library/i }).first().click();
await page.locator('.compare-card', { hasText: 'Internal resistance' }).first().getByRole('button', { name: 'Open' }).click();
await page.waitForTimeout(1300);
await page.screenshot({ path: '/tmp/dock2.png' });
// press "Realistic" and capture ripple
const tab = page.getByRole('tab', { name: 'Realistic' });
const b = await tab.boundingBox();
await page.mouse.move(b.x + b.width * 0.5, b.y + b.height * 0.5);
await page.mouse.down();
await page.waitForTimeout(240);
await page.screenshot({ path: '/tmp/ripple2.png', clip: { x: 300, y: 80, width: 420, height: 80 } });
await page.mouse.up();
await page.waitForTimeout(500);
// mobile tab press
const ctx = await browser.newContext({ ...devices['iPhone 13'], browserName: 'chromium', deviceScaleFactor: 2 });
const mp = await ctx.newPage();
await mp.goto('http://localhost:4173/', { waitUntil: 'networkidle' });
await mp.waitForTimeout(500);
const tb = mp.locator('.mobile-tab').nth(1);
const tbb = await tb.boundingBox();
await mp.mouse.move(tbb.x + tbb.width / 2, tbb.y + tbb.height / 2);
await mp.mouse.down();
await mp.waitForTimeout(240);
await mp.screenshot({ path: '/tmp/ripple-mobile.png', clip: { x: 0, y: 540, width: 390, height: 104 } });
await mp.mouse.up();
await browser.close();
